"""Informed search for COS30019 Tree Based Search: GBFS and A*.

Both methods receive a RouteProblem and return the same SearchResult.
The shared best-first frontier follows the course's Problem/Node structure.
"""
import heapq
from itertools import count
from route_problem import Node, make_result


def best_first_graph_search(problem, greedy=False, trace=False):
    """Priority-queue search shared by GBFS and A*.

    GBFS: f(n) = geometric h(n).
    A*:   f(n) = travelled cost g(n) + admissible cost h(n).

    Successors are generated by ascending ID. An insertion counter preserves
    chronological order between equal-priority nodes on different branches.
    """
    heuristic = problem.heuristics('greedy' if greedy else 'cost')
    root = Node(problem.initial)
    insertion_order = count()
    frontier = [(heuristic[root.state], next(insertion_order), root)]
    best_cost = {root.state: root.path_cost}
    created, expanded = 1, 0
    history = []

    while frontier:
        priority, _, node = heapq.heappop(frontier)

        # A cheaper replacement might have made this A* queue entry obsolete.
        if not greedy and node.path_cost != best_cost[node.state]:
            continue

        reached_goal = problem.goal_test(node.state)
        if trace:
            history.append({
                'step': len(history) + 1,
                'state': node.state,
                'g': node.path_cost,
                'priority': priority,
                'status': 'goal' if reached_goal else 'expanded',
            })
        # Check after removing the best entry, not when first generating a goal.
        if reached_goal:
            return make_result(node, created, expanded, trace=history)

        expanded += 1
        for action in problem.actions(node.state):
            next_state = problem.result(node.state, action)
            candidate_cost = problem.path_cost(
                node.path_cost, node.state, action, next_state)

            if next_state in best_cost:
                if greedy or candidate_cost >= best_cost[next_state]:
                    continue

            # Count only allocated node records, including A* replacements.
            child = node.child_node(problem, action)
            created += 1
            best_cost[next_state] = child.path_cost
            score = heuristic[next_state]
            if not greedy:
                score += child.path_cost
            heapq.heappush(frontier, (score, next(insertion_order), child))

    return make_result(None, created, expanded, trace=history)


def greedy_best_first_search(problem, trace=False):
    """GBFS chooses the node appearing closest to any destination.

    It suppresses repeated states to avoid cycles on finite graphs. It does
    not guarantee a lowest-cost route or a route with the fewest moves.
    """
    return best_first_graph_search(problem, greedy=True, trace=trace)


def astar_search(problem, trace=False):
    """A* minimizes cost with the shared model's admissible heuristic.

    RouteProblem scales nearest-goal Euclidean distance into cost units using
    the minimum edge-cost/geometric-length ratio. This permits arbitrary
    nonnegative weights rather than assuming weights equal physical distances.
    Cheaper routes may replace queued or previously expanded states.
    """
    return best_first_graph_search(problem, greedy=False, trace=trace)


# Short names are available if the group prefers them during integration.
gbfs = greedy_best_first_search
astar = astar_search
