"""Dijkstra and Yen's algorithm for up to K shortest loopless routes.

All edge weights represent estimated travel time in seconds and must be
finite, nonnegative values. Each road link is directed unless the input graph
contains a reverse edge as well.
"""

from __future__ import annotations

import heapq
import math
from dataclasses import dataclass
from itertools import count
from typing import Mapping


Graph = Mapping[int, Mapping[int, float]]


@dataclass(frozen=True)
class Route:
    nodes: tuple[int, ...]
    travel_time_seconds: float

    @property
    def travel_time_minutes(self) -> float:
        return self.travel_time_seconds / 60.0


def _validate_graph(graph: Graph) -> None:
    for node, neighbours in graph.items():
        if type(node) is not int:
            raise ValueError("All SCATS graph node IDs must be integers.")
        for neighbour, weight in neighbours.items():
            if type(neighbour) is not int:
                raise ValueError("All SCATS graph node IDs must be integers.")
            if neighbour not in graph:
                raise ValueError(f"Edge {node}->{neighbour} points to an unknown node.")
            if not math.isfinite(weight) or weight < 0:
                raise ValueError("Travel-time edge weights must be finite and nonnegative.")


def _path_cost(graph: Graph, path: tuple[int, ...]) -> float:
    total = 0.0
    for left, right in zip(path, path[1:]):
        try:
            total += graph[left][right]
        except KeyError as error:
            raise ValueError(f"Path contains a missing edge: {left}->{right}") from error
    return total


def dijkstra_shortest_path(
    graph: Graph,
    source: int,
    destination: int,
    *,
    excluded_nodes: set[int] | None = None,
    excluded_edges: set[tuple[int, int]] | None = None,
) -> Route | None:
    """Return the lowest-travel-time loopless path, or None when unreachable."""

    _validate_graph(graph)
    if source not in graph or destination not in graph:
        raise KeyError("Source and destination must both exist in the road graph.")

    banned_nodes = set(excluded_nodes or ())
    banned_edges = set(excluded_edges or ())
    if source in banned_nodes or destination in banned_nodes:
        return None

    insertion_order = count()
    # Heap ordering is: cost, insertion order, path, current node. The counter
    # avoids comparing path metadata when two costs are equal.
    frontier: list[tuple[float, int, tuple[int, ...], int]] = [
        (0.0, next(insertion_order), (source,), source)
    ]
    best: dict[int, tuple[float, tuple[int, ...]]] = {source: (0.0, (source,))}

    while frontier:
        cost, _, path, node = heapq.heappop(frontier)
        if best.get(node) != (cost, path):
            continue
        if node == destination:
            return Route(nodes=path, travel_time_seconds=cost)

        for neighbour, weight in sorted(graph[node].items()):
            if neighbour in banned_nodes or (node, neighbour) in banned_edges:
                continue
            if neighbour in path:
                continue
            candidate_path = path + (neighbour,)
            candidate_cost = cost + weight
            current_best = best.get(neighbour)
            if current_best is None or (candidate_cost, candidate_path) < current_best:
                best[neighbour] = (candidate_cost, candidate_path)
                heapq.heappush(
                    frontier,
                    (
                        candidate_cost,
                        next(insertion_order),
                        candidate_path,
                        neighbour,
                    ),
                )

    return None


def k_shortest_loopless_paths(
    graph: Graph, source: int, destination: int, k: int = 5
) -> list[Route]:
    """Return up to ``k`` distinct, loopless routes ranked by travel time.

    This is Yen's K-shortest loopless paths algorithm. Dijkstra is run for the
    initial shortest path and for each spur path generated by Yen's algorithm.
    """

    if type(k) is not int or k < 1:
        raise ValueError("k must be a positive integer.")
    _validate_graph(graph)
    if source not in graph or destination not in graph:
        raise KeyError("Source and destination must both exist in the road graph.")

    first_route = dijkstra_shortest_path(graph, source, destination)
    if first_route is None:
        return []
    accepted: list[Route] = [first_route]
    candidates: list[tuple[float, tuple[int, ...]]] = []
    candidate_paths: set[tuple[int, ...]] = set()

    for _ in range(1, k):
        previous_path = accepted[-1].nodes

        for spur_index in range(len(previous_path) - 1):
            root_path = previous_path[: spur_index + 1]
            spur_node = root_path[-1]
            removed_edges: set[tuple[int, int]] = set()

            # Remove the next edge from every accepted route sharing this root.
            for route in accepted:
                route_nodes = route.nodes
                if (
                    len(route_nodes) > spur_index + 1
                    and route_nodes[: spur_index + 1] == root_path
                ):
                    removed_edges.add(
                        (route_nodes[spur_index], route_nodes[spur_index + 1])
                    )

            # Prevent the spur path from revisiting nodes in the root prefix.
            removed_nodes = set(root_path[:-1])
            spur_route = dijkstra_shortest_path(
                graph,
                spur_node,
                destination,
                excluded_nodes=removed_nodes,
                excluded_edges=removed_edges,
            )
            if spur_route is None:
                continue

            total_nodes = root_path[:-1] + spur_route.nodes
            if total_nodes in candidate_paths or any(
                route.nodes == total_nodes for route in accepted
            ):
                continue

            total_cost = _path_cost(graph, total_nodes)
            heapq.heappush(candidates, (total_cost, total_nodes))
            candidate_paths.add(total_nodes)

        if not candidates:
            break

        next_cost, next_nodes = heapq.heappop(candidates)
        candidate_paths.remove(next_nodes)
        accepted.append(Route(nodes=next_nodes, travel_time_seconds=next_cost))

    return accepted
